<?php

use App\Http\Controllers\AuthController;
use App\Http\Controllers\BookingController;
use App\Http\Controllers\EventController;
use App\Http\Controllers\TicketController;
use App\Http\Controllers\UserController;
use App\Http\Controllers\VenueController;
use Illuminate\Support\Facades\Route;

// Public routes: no token needed.
Route::post('/auth/register', [AuthController::class, 'register']);
Route::post('/auth/login', [AuthController::class, 'login'])->middleware('throttle:login');

// Anyone can browse venues and events.
Route::apiResource('venues', VenueController::class)->only(['index', 'show']);
Route::apiResource('events', EventController::class)->only(['index', 'show']);

// External systems (for example a door scanner): API key, no user login.
Route::get('/tickets/{reference}', [TicketController::class, 'show'])->middleware('api.key');

// Protected routes: a valid JWT is required.
Route::middleware('auth:api')->group(function () {
    Route::get('/auth/me', [AuthController::class, 'me']);
    Route::post('/auth/refresh', [AuthController::class, 'refresh']);
    Route::post('/auth/logout', [AuthController::class, 'logout']);

    // Users: admin only.
    Route::apiResource('users', UserController::class)->middleware('role:admin');

    // Venues and events: admins and organisers create and update.
    Route::middleware('role:admin,organiser')->group(function () {
        Route::apiResource('venues', VenueController::class)->only(['store', 'update']);
        Route::apiResource('events', EventController::class)->only(['store', 'update', 'destroy']);
    });

    // Only an admin can delete a venue.
    Route::delete('/venues/{venue}', [VenueController::class, 'destroy'])->middleware('role:admin');

    // Bookings: every role can list, view and update what it is allowed to see.
    Route::apiResource('bookings', BookingController::class)->only(['index', 'show', 'update']);
    Route::post('/bookings', [BookingController::class, 'store'])->middleware('role:customer');
    Route::delete('/bookings/{booking}', [BookingController::class, 'destroy'])->middleware('role:admin');

    // QR code for a booking, generated by a third-party API.
    Route::get('/bookings/{booking}/qr', [BookingController::class, 'qr']);
});
